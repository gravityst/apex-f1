/** Normalised lap distance -> metres for a given circuit. */
export function toMetres(circuit, u) {
  const L = circuit && circuit.lengthTarget ? circuit.lengthTarget : 0;
  return (((u % 1) + 1) % 1) * L;
}

/** Metres -> normalised lap distance for a given circuit. */
export function toLapFraction(circuit, metres) {
  const L = circuit && circuit.lengthTarget ? circuit.lengthTarget : 1;
  return (((metres / L) % 1) + 1) % 1;
}

export const CIRCUIT_IDS = CIRCUITS.map((c) => c.id);

export const DEFAULT_CIRCUIT_ID = 'aurora-bay';

/** Look up a circuit by id. Falls back to the first circuit, never returns null. */
export function getCircuit(id) {
  if (!id) return CIRCUITS[0];
  for (let i = 0; i < CIRCUITS.length; i++) if (CIRCUITS[i].id === id) return CIRCUITS[i];
  return CIRCUITS[0];
}

/** Index of a circuit in CIRCUITS, or 0 when unknown. */
export function getCircuitIndex(id) {
  for (let i = 0; i < CIRCUITS.length; i++) if (CIRCUITS[i].id === id) return i;
  return 0;
}

/** Next circuit in the calendar, wrapping. */
export function nextCircuit(id) {
  return CIRCUITS[(getCircuitIndex(id) + 1) % CIRCUITS.length];
}

/**
 * Nearest named turn at (or just before) a normalised lap position.
 * Returns null when the circuit carries no turn table.
 */
export function turnAt(circuit, u) {
  const turns = circuit && circuit.turns;
  if (!turns || !turns.length) return null;
  const p = (((u % 1) + 1) % 1);
  let best = turns[turns.length - 1];
  let bestGap = Infinity;
  for (let i = 0; i < turns.length; i++) {
    const gap = (p - turns[i].at + 1) % 1;
    if (gap < bestGap) { bestGap = gap; best = turns[i]; }
  }
  return best;
}

/** The turn coming up next, looking forward from u. */
export function nextTurn(circuit, u) {
  const turns = circuit && circuit.turns;
  if (!turns || !turns.length) return null;
  const p = (((u % 1) + 1) % 1);
  let best = turns[0];
  let bestGap = Infinity;
  for (let i = 0; i < turns.length; i++) {
    const gap = (turns[i].at - p + 1) % 1;
    if (gap > 1e-6 && gap < bestGap) { bestGap = gap; best = turns[i]; }
  }
  return best;
}

/** 1-based sector number (1..3) for a normalised lap position. */
export function sectorAt(circuit, u) {
  const s = (circuit && circuit.sectors) || [0.34, 0.68];
  const p = (((u % 1) + 1) % 1);
  return p < s[0] ? 1 : p < s[1] ? 2 : 3;
}

/** True when u lies inside one of the circuit's DRS activation zones. */
export function inDRSZone(circuit, u) {
  const zones = (circuit && circuit.drsZones) || [];
  const p = (((u % 1) + 1) % 1);
  for (let i = 0; i < zones.length; i++) {
    const z = zones[i];
    if (z.start <= z.end ? (p >= z.start && p <= z.end) : (p >= z.start || p <= z.end)) return i;
  }
  return -1;
}

/** Compact one-line summary, handy for menus and telemetry headers. */
export function describeCircuit(circuit) {
  if (!circuit) return '';
  return circuit.name + ' — ' + circuit.location + ', ' + circuit.country
    + ' · ' + (circuit.lengthTarget / 1000).toFixed(3) + ' km · '
    + circuit.turnCount + ' turns · ' + circuit.laps + ' laps';
}
